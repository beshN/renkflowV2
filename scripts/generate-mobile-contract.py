"""Generate native protocol constants from the checked-in OpenAPI source."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
contract = json.loads((root / 'contracts/mobile/openapi.json').read_text())
version = contract['info']['version']
base = contract['servers'][0]['url']
(root / 'apps/native-android/app/src/main/java/com/renkflow/field/data/MobileContract.kt').write_text(f'''// Generated by scripts/generate-mobile-contract.py. Do not edit.
package com.renkflow.field.data
object MobileContract {{ const val version = "{version}"; const val basePath = "{base}" }}
''')
(root / 'apps/native-ios/RenkflowField/Core/MobileContract.swift').write_text(f'''// Generated by scripts/generate-mobile-contract.py. Do not edit.
import Foundation
enum MobileContract {{ static let version = "{version}"; static let basePath = "{base}" }}
''')
